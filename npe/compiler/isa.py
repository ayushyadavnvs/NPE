"""NPE instruction set: one instruction per layer, every field 16 bits.

The C mirror is npe/isa/npe_isa.h (generated by `python3 -m npe.compiler.isa`);
field order here is the order in the binary program and in the C struct.

Semantics (the NumPy reference in npe/ref/isa_ref.py is the definition):

  Tensors live in buffers as HWC element arrays. A tensor view is
  (buf, base, H, W, C, pix_stride, ch_off): element (y, x, c) is at
  base + (y * W + x) * pix_stride + ch_off + c. Splitting a tensor is a view
  with a channel offset; concat is two layers writing different ch_off of the
  same output tensor.

  op CONV      out = act(requant(conv(A, w) + bias)), any kh x kw, stride,
               asymmetric padding, groups (groups == C: depthwise; 1x1 on a
               1x1 map: fully connected). raw_out skips requant and writes the
               int32 accumulator (logits).
  op POOL_MAX  max over the window; padding is ignored.
  op POOL_AVG  reserved (step 2).
  op GAP       per-channel sum over H x W, int32 out into buffer V (the
               1/(H*W) is folded into the next layer's scale).
  op ADD       reserved (a standalone add; residuals use the ADD epilogue).

  epilogue INTERLEAVE  out channel 2i = B channel i, 2i + 1 = result channel
               i (concat + channel shuffle of two branches, no extra pass).
               The output view may alias B (in place).
  epilogue ADD residual add fused into a CONV: with b the B operand channel
               (b_signed), out = clamp((acc * M + b * Mb + 2^(S-1)) >> S),
               acc = conv + bias, M, Mb, S per output channel. The clamp
               (activation included) applies to the sum. The output view may
               be the B view itself (in place).

  act RELU6    clamp to [0, act_max]; act_max is 6.0 in the output's
               quantized scale.

  Precision: a_in_bits / w_bits / a_out_bits in {4, 8}; 32 for an int32
  tensor (GAP output, raw logits). Requant clamps to the out range:
  unsigned [0, 2^b - 1] when act is RELU (or the input stage of an unsigned
  tensor), signed [-2^(b-1), 2^(b-1) - 1] otherwise.
"""
from dataclasses import dataclass, fields

# ops
OP_CONV, OP_POOL_MAX, OP_POOL_AVG, OP_GAP, OP_ADD = range(5)
# epilogues
EPI_NONE, EPI_INTERLEAVE, EPI_ADD = range(3)
# activations
ACT_NONE, ACT_RELU, ACT_RELU6 = range(3)
# padding value
PAD_ZERO, PAD_CONST = range(2)  # CONST: per-input-channel value from params
# buffers: on-chip arena regions, plus the two AXI streams. V holds int32
# vectors (GAP output, fc input); the others hold 8-bit tensors.
BUF_IN, BUF_OUT, BUF_S0, BUF_A, BUF_B, BUF_C, BUF_V = range(7)
BUF_NAMES = ["IN", "OUT", "S0", "A", "B", "C", "V"]


@dataclass
class Instr:
    op: int = OP_CONV
    epi: int = EPI_NONE
    act: int = ACT_NONE
    act_max: int = 0     # RELU6 upper clamp (quantized 6.0)
    # geometry
    kh: int = 1
    kw: int = 1
    sh: int = 1
    sw: int = 1
    pad_t: int = 0
    pad_l: int = 0
    pad_b: int = 0
    pad_r: int = 0
    pad_mode: int = PAD_ZERO
    groups: int = 1
    # input A
    a_buf: int = BUF_A
    a_base: int = 0
    a_h: int = 1
    a_w: int = 1
    a_c: int = 1
    a_pix: int = 0       # pixel stride; 0 = a_c
    a_off: int = 0
    a_signed: int = 0
    a_bits: int = 8
    # input B (epilogue operand)
    b_buf: int = BUF_A
    b_base: int = 0
    b_pix: int = 0
    b_off: int = 0
    b_signed: int = 0
    # output
    o_buf: int = BUF_A
    o_base: int = 0
    o_h: int = 1
    o_w: int = 1
    o_c: int = 1         # channels this layer computes (before INTERLEAVE)
    o_pix: int = 0       # 0 = total output channels
    o_off: int = 0
    o_signed: int = 0
    o_bits: int = 8
    raw_out: int = 0
    # parameters
    w_bits: int = 8
    w_base: int = 0      # parameter block index (reference) / word base (hw)
    q_base: int = 0

    def out_channels(self):
        return 2 * self.o_c if self.epi == EPI_INTERLEAVE else self.o_c


FIELDS = [f.name for f in fields(Instr)]


def c_header():
    lines = [
        "// Generated by npe/compiler/isa.py. Do not edit.",
        "#ifndef NPE_ISA_H_",
        "#define NPE_ISA_H_",
        "",
        "#include <stdint.h>",
        "",
        "enum { NPE_OP_CONV, NPE_OP_POOL_MAX, NPE_OP_POOL_AVG, NPE_OP_GAP, NPE_OP_ADD };",
        "enum { NPE_EPI_NONE, NPE_EPI_INTERLEAVE, NPE_EPI_ADD };",
        "enum { NPE_ACT_NONE, NPE_ACT_RELU, NPE_ACT_RELU6 };",
        "enum { NPE_PAD_ZERO, NPE_PAD_CONST };",
        "enum { " + ", ".join(f"NPE_BUF_{n}" for n in BUF_NAMES) + " };",
        "",
        f"// One layer. {len(FIELDS)} x 16-bit fields; field order = binary program order.",
        "struct npe_instr_t {",
    ]
    lines += [f"  uint16_t {n};" for n in FIELDS]
    lines += ["};", "", f"#define NPE_INSTR_FIELDS {len(FIELDS)}", "",
              "// X(name, index) for every field: field i is bits [16i + 15 : 16i] of a",
              "// packed instruction word.",
              "#define NPE_INSTR_FIELD_LIST(X) \\"]
    lines += [f"  X({n}, {i})" + (" \\" if i < len(FIELDS) - 1 else "")
              for i, n in enumerate(FIELDS)]
    lines += ["", "#endif // NPE_ISA_H_", ""]
    return "\n".join(lines)


def encode(prog):
    """Program as little-endian uint16 words, len(FIELDS) per instruction."""
    import struct
    out = b""
    for ins in prog:
        vals = [getattr(ins, n) for n in FIELDS]
        assert all(0 <= v < 1 << 16 for v in vals), ins
        out += struct.pack(f"<{len(vals)}H", *vals)
    return out


if __name__ == "__main__":
    import os
    path = os.path.join(os.path.dirname(__file__), "..", "isa", "npe_isa.h")
    with open(path, "w") as f:
        f.write(c_header())
    print("wrote", os.path.normpath(path))
