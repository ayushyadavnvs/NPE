#!/usr/bin/env python3
"""Turns data/weights.bin into C headers for the HLS layers.

Example (from new_accelrator):
  python3 tools/gen_weights.py                       # data/weights.bin -> src/weights/
  python3 tools/gen_weights.py --bin other.bin --out src/weights

Writes:
  src/weights/stem_weights.h  conv1 laid out for the stem engine
      (src/layers/stem.h): STEM_GROUPS groups of STEM_PAR output channels, each
      row holding STEM_PAR x 27 weights. Within one output channel the tap
      order is (ky * 3 + kx) * 3 + ci, which matches the packed window.
  src/weights/unit_program.h  the network program after the stem: 16 shuffle
      units, conv5 and the head (global average pool + fc), as a layer table
      with buffer ids, sizes and weight base offsets, plus memory sizes. It
      depends only on the network shape, not on the weight values.
  data/unit_weights.bin       run-time load image for the unit engine
      (src/layers/units.h), little-endian 64-bit words in this order:
        PW words   UNIT_PW_WORDS x 16  (8 in x 16 out int8, byte k*8+m = w[out k][in m])
        DW words   UNIT_DW_WORDS x 9   (8 channels x 9 taps int8, byte k*9+t)
        PW quant   UNIT_QP_WORDS x 18  (16 lanes: i32 bias, i32 M, u8 S)
        DW quant   UNIT_QD_WORDS x 9   (8 lanes:  i32 bias, i32 M, u8 S)
        FC words   UNIT_FC_WORDS x NUM_CLASSES (8 channels x NUM_CLASSES int8,
                   byte c*8+k = w[class c][channel 8g+k], one beat per class)
        FC bias    FC_B_BEATS = ceil(NUM_CLASSES / 2)  (i32 per class, class 0
                   first, zero-padded to whole 64-bit beats)
      New weights with the same shapes need only a new load image, no
      resynthesis.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "golden"))

from model_def import NUM_CLASSES, STAGE_OUT, units  # noqa: E402
from quantize import read_bin  # noqa: E402
import numpy as np  # noqa: E402

STEM_PAR = 4  # output channels computed per cycle

# Unit engine geometry (must match src/layers/units.h).
CW = 8        # channels per buffer word
PW_OUT = 16   # pointwise output channels per cycle (8 in x 16 out)
FC_B_BEATS = (NUM_CLASSES + 1) // 2  # 64-bit beats of fc bias (2 x i32 each)
BUF = {"X": 0, "T1": 1, "T2": 2, "B1": 3, "B2": 4}
KIND_PW, KIND_DW, KIND_MERGE, KIND_HEAD = 0, 1, 2, 3


def rows(values, per_line=12):
    vals = [str(int(v)) for v in values]
    return ",\n    ".join(", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line))


def table(ctype, name, groups):
    body = ",\n  ".join("{" + rows(g) + "}" for g in groups)
    return f"static const {ctype} {name}[STEM_GROUPS][{len(groups[0])}] = {{\n  {body}}};\n"


def stem_header(layers, pad):
    L = next(l for l in layers if l["name"] == "conv1")
    assert L["kind"] == "std" and L["k"] == 3 and L["stride"] == 2 and L["cin"] == 3
    assert L["relu"], "stem engine assumes ReLU after conv1"
    cout = L["cout"]
    assert cout % STEM_PAR == 0
    assert L["S"].min() >= 1 and L["S"].max() <= 63, "shift must fit rq_shift_t"
    assert L["M"].min() >= 0 and L["M"].max() < 2**31
    ngroups = cout // STEM_PAR
    # w[o][ci][ky][kx] -> w[o][(ky*3+kx)*3+ci]
    w = L["w"].transpose(0, 2, 3, 1).reshape(cout, 27)
    wg = [w[g * STEM_PAR:(g + 1) * STEM_PAR].reshape(-1) for g in range(ngroups)]
    grp = lambda a: [a[g * STEM_PAR:(g + 1) * STEM_PAR] for g in range(ngroups)]
    out = [
        "// Generated by tools/gen_weights.py from data/weights.bin. Do not edit.",
        "#ifndef BD_WEIGHTS_STEM_WEIGHTS_H_",
        "#define BD_WEIGHTS_STEM_WEIGHTS_H_",
        "",
        '#include "../types.h"',
        "",
        f"#define STEM_COUT {cout}",
        f"#define STEM_PAR {STEM_PAR}",
        f"#define STEM_GROUPS {ngroups}",
        f"#define STEM_TAPS 27",
        "",
        "// Per-channel pad pixel (folded input mean), R, G, B.",
        f"static const act_t STEM_PAD[3] = {{{', '.join(str(int(p)) for p in pad)}}};",
        "",
        "// conv1 weights: [group][j * 27 + (ky * 3 + kx) * 3 + ci], output channel",
        "// o = group * STEM_PAR + j.",
        table("wgt_t", "STEM_W", wg),
        table("bias_t", "STEM_BIAS", grp(L["bias"])),
        table("rq_mult_t", "STEM_M", grp(L["M"])),
        table("rq_shift_t", "STEM_S", grp(L["S"])),
        "#endif // BD_WEIGHTS_STEM_WEIGHTS_H_",
        "",
    ]
    return "\n".join(out)


class UnitImage:
    """Builds the unit layer program and the matching weight load image."""

    def __init__(self, layers):
        self.L = {l["name"]: l for l in layers}
        self.prog = []
        self.pw, self.dw, self.qp, self.qd, self.fc = [], [], [], [], []
        self.fc_bias = None
        self.buf_words = dict.fromkeys(BUF, 0)
        self.cycles = 0

    def _use(self, buf, words):
        self.buf_words[buf] = max(self.buf_words[buf], words)

    def pw_layer(self, name, src, dst, size, cin_g, src_off, src_tot, signed, merge=False,
                 out_name=None):
        """dst "X" writes the first half of each X pixel (2 * cout_g words per
        pixel). With merge, the layer is a unit's pw2: it writes concat +
        channel shuffle of (X first half, its own output) straight into X, so
        no separate merge pass and no B1/B2 buffers are needed (see unit_pw)."""
        assert not merge or (dst == "X" and cin_g >= 2), "merge-on-write needs cin_g >= 2"
        L = self.L[name]
        assert L["kind"] == "pw" and L["relu"]
        cout, cin = L["cout"], L["cin"]
        assert cin == cin_g * CW and cout % CW == 0
        assert cin_g >= 1
        cout_g = cout // CW
        n_og2 = (cout + PW_OUT - 1) // PW_OUT
        w = L["w"].reshape(cout, cin)
        w_base, q_base = len(self.pw), len(self.qp)
        for og2 in range(n_og2):
            for ig in range(cin_g):
                blk = np.zeros((PW_OUT, CW), np.int8)
                o0 = og2 * PW_OUT
                n = min(PW_OUT, cout - o0)
                blk[:n] = w[o0:o0 + n, ig * CW:(ig + 1) * CW]
                self.pw.append(blk.reshape(-1))
            self.qp.append(self._quant(L, og2 * PW_OUT, PW_OUT))
        self._use(dst, size * size * cout_g * (2 if dst == "X" else 1))
        self.prog.append(dict(name=out_name or name, kind=KIND_PW, src=src, dst=dst, aux="X",
                              merge=merge,
                              size=size,
                              stride=1, cin_g=cin_g, src_off=src_off, src_tot=src_tot,
                              cout_g=cout_g, w_base=w_base, q_base=q_base, signed=signed))
        self.cycles += size * size * n_og2 * cin_g

    def dw_layer(self, name, src, dst, size, stride):
        L = self.L[name]
        assert L["kind"] == "dw" and not L["relu"] and L["stride"] == stride
        assert stride == 1 or size % 2 == 0
        c = L["cout"]
        g = c // CW
        w = L["w"].reshape(c, 9)
        w_base, q_base = len(self.dw), len(self.qd)
        for i in range(g):
            self.dw.append(w[i * CW:(i + 1) * CW].reshape(-1))
            self.qd.append(self._quant(L, i * CW, CW))
        out = size // stride
        self._use(dst, out * out * g)
        self.prog.append(dict(name=name, kind=KIND_DW, src=src, dst=dst, aux="X", size=size,
                              stride=stride, cin_g=g, src_off=0, src_tot=g, cout_g=g,
                              w_base=w_base, q_base=q_base, signed=False))
        self.cycles += g * (size + 1) * (size + 1)

    def merge(self, name, aux, size, half_g, aux_tot):
        self._use("X", size * size * 2 * half_g)
        self.prog.append(dict(name=name, kind=KIND_MERGE, src="B2", dst="X", aux=aux, size=size,
                              stride=1, cin_g=half_g, src_off=0, src_tot=aux_tot,
                              cout_g=2 * half_g, w_base=0, q_base=0, signed=False))
        self.cycles += size * size * 2 * half_g

    @staticmethod
    def _quant(L, o0, lanes):
        n = min(lanes, L["cout"] - o0)
        bias = np.zeros(lanes, np.int64)
        M = np.zeros(lanes, np.int64)
        S = np.ones(lanes, np.int64)  # padding lanes: M = 0, S = 1 -> output 0
        bias[:n], M[:n], S[:n] = L["bias"][o0:o0 + n], L["M"][o0:o0 + n], L["S"][o0:o0 + n]
        assert S.min() >= 1 and S.max() <= 63 and M.min() >= 0 and M.max() < 2**31
        return bias, M, S

    def build(self):
        size, c = 56, STAGE_OUT[0]
        self._use("X", size * size * c // CW)
        for prefix, down in units():
            st = int(prefix[1])
            cout = STAGE_OUT[st - 1]
            hg = cout // 2 // CW
            if down:
                g = c // CW
                # pw1 runs before b1.pw, so b1.pw can write branch 1 over the
                # (fully consumed) unit input in X.
                self.dw_layer(f"{prefix}.b1.dw", "X", "T2", size, 2)
                self.pw_layer(f"{prefix}.pw1", "X", "T1", size, g, 0, g, False)
                self.pw_layer(f"{prefix}.b1.pw", "T2", "X", size // 2, g, 0, g, True)
                self.dw_layer(f"{prefix}.dw", "T1", "T2", size, 2)
                size //= 2
                self.pw_layer(f"{prefix}.pw2", "T2", "X", size, hg, 0, hg, True,
                              merge=True, out_name=f"{prefix}.out")
            else:
                self.pw_layer(f"{prefix}.pw1", "X", "T1", size, hg, hg, 2 * hg, False)
                self.dw_layer(f"{prefix}.dw", "T1", "T2", size, 1)
                self.pw_layer(f"{prefix}.pw2", "T2", "X", size, hg, 0, hg, True,
                              merge=True, out_name=f"{prefix}.out")
            c = cout
        self.out_size, self.out_ch = size, c
        self.num_unit_layers = len(self.prog)
        # conv5 on the pointwise engine, then global average pool + fc.
        self.pw_layer("conv5", "X", "T1", size, c // CW, 0, c // CW, False)
        L = self.L["fc"]
        assert L["kind"] == "fc" and L["cout"] == NUM_CLASSES, \
            f"fc has {L['cout']} outputs, NUM_CLASSES is {NUM_CLASSES}"
        g5 = L["cin"] // CW
        w = L["w"].reshape(NUM_CLASSES, L["cin"])
        for g in range(g5):
            self.fc.append(w[:, g * CW:(g + 1) * CW].reshape(-1))
        self.fc_bias = np.zeros(2 * FC_B_BEATS, np.int64)
        self.fc_bias[:NUM_CLASSES] = L["bias"]
        self.prog.append(dict(name="logits", kind=KIND_HEAD, src="T1", dst="X", aux="X",
                              size=size, stride=1, cin_g=g5, src_off=0, src_tot=g5, cout_g=0,
                              w_base=0, q_base=0, signed=False))
        self.cycles += size * size * g5 + g5
        return self

    def load_image(self):
        words = []

        def bytes_to_u64(b):
            b = np.asarray(b, np.int64).astype(np.uint8).tobytes()
            words.extend(np.frombuffer(b, "<u8").tolist())

        for blk in self.pw:
            bytes_to_u64(blk)
        for blk in self.dw:
            bytes_to_u64(blk)
        for bias, M, S in self.qp + self.qd:
            b = (bias.astype("<i4").tobytes() + M.astype("<i4").tobytes()
                 + S.astype(np.uint8).tobytes())
            words.extend(np.frombuffer(b, "<u8").tolist())
        for blk in self.fc:
            bytes_to_u64(blk)
        words.extend(np.frombuffer(self.fc_bias.astype("<i4").tobytes(), "<u8").tolist())
        assert len(words) == self.load_words()
        return np.array(words, np.uint64)

    def load_words(self):
        return (len(self.pw) * 16 + len(self.dw) * 9 + len(self.qp) * 18 + len(self.qd) * 9
                + len(self.fc) * NUM_CLASSES + FC_B_BEATS)

    def header(self):
        B = self.buf_words
        out = [
            "// Generated by tools/gen_weights.py. Do not edit.",
            "// Shuffle-unit layer program for src/layers/units.h. It depends only on",
            "// the network shape; the weight values come from data/unit_weights.bin.",
            "#ifndef BD_WEIGHTS_UNIT_PROGRAM_H_",
            "#define BD_WEIGHTS_UNIT_PROGRAM_H_",
            "",
            "// Program: UNIT_NUM_LAYERS shuffle-unit layers, then conv5, then the head.",
            f"#define UNIT_NUM_LAYERS {self.num_unit_layers}",
            f"#define NET_NUM_LAYERS {len(self.prog)}",
            f"#define UNIT_PW_WORDS {len(self.pw)}",
            f"#define UNIT_DW_WORDS {len(self.dw)}",
            f"#define UNIT_QP_WORDS {len(self.qp)}",
            f"#define UNIT_QD_WORDS {len(self.qd)}",
            f"#define UNIT_FC_WORDS {len(self.fc)}",
            f"#define UNIT_NUM_CLASSES {NUM_CLASSES}",
            f"#define UNIT_LOAD_WORDS {self.load_words()}",
            "",
            "// Feature buffer sizes in 8-channel words.",
        ] + [f"#define UNIT_BUF_{k}_WORDS {max(v, 1)}" for k, v in B.items()] + [
            "",
            f"// Unit output: s4u3.out, {self.out_size}x{self.out_size}x{self.out_ch}.",
            f"#define UNIT_OUT_SIZE {self.out_size}",
            f"#define UNIT_OUT_GROUPS {self.out_ch // CW}",
            f"// Ideal engine cycles per frame, units + conv5 + head (no pipeline fill): {self.cycles}",
            f"#define UNIT_IDEAL_CYCLES {self.cycles}",
            "",
            "// kind, src, dst, aux, size, stride, cin_g, src_off, src_tot, cout_g,",
            "// w_base, q_base, in_signed, merge",
            "static const unit_layer_t UNIT_PROGRAM[NET_NUM_LAYERS] = {",
        ]
        for e in self.prog:
            out.append("    {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d}, // %s" % (
                e["kind"], BUF[e["src"]], BUF[e["dst"]], BUF[e["aux"]], e["size"], e["stride"],
                e["cin_g"], e["src_off"], e["src_tot"], e["cout_g"], e["w_base"], e["q_base"],
                int(e["signed"]), int(e.get("merge", False)), e["name"]))
        out += ["};", "", "#ifndef __SYNTHESIS__",
                "// Golden tensor name written by each layer (for the testbench).",
                "static const char *const UNIT_LAYER_NAMES[NET_NUM_LAYERS] = {"]
        out += [f'    "{e["name"]}",' for e in self.prog]
        out += ["};", "#endif", "", "#endif // BD_WEIGHTS_UNIT_PROGRAM_H_", ""]
        return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bin", default=os.path.join(ROOT, "data", "weights.bin"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "weights"))
    ap.add_argument("--image", default=os.path.join(ROOT, "data", "unit_weights.bin"),
                    help="unit engine load image to write")
    args = ap.parse_args()
    layers, pad, _ = read_bin(args.bin)
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "stem_weights.h")
    with open(path, "w") as f:
        f.write(stem_header(layers, pad))
    print("wrote", path)
    img = UnitImage(layers).build()
    path = os.path.join(args.out, "unit_program.h")
    with open(path, "w") as f:
        f.write(img.header())
    print("wrote", path)
    words = img.load_image()
    words.astype("<u8").tofile(args.image)
    print("wrote %s (%d words), unit engine ideal cycles %d" % (args.image, len(words), img.cycles))


if __name__ == "__main__":
    main()
